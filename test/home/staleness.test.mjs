import { test, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHarness } from "../harness/index.mjs";

const script = join(dirname(fileURLToPath(import.meta.url)), "../../scripts/home/staleness.mjs");
const HOME = "me/home";
const NOW = "2026-01-10T12:00:00Z";
const ago = (h) => new Date(Date.parse(NOW) - h * 3600e3).toISOString();
const AI = "> *This was generated by AI: alpha Goal agent.*";
const lastRun = (updated_at, body = `${AI}\n\n## Last run\n\nquick exit yes`) => ({ body, updated_at, created_at: ago(100) });
const HALT = "<!-- goal-agent:halted -->";

const harnesses = [];
const dirs = [];
after(() => { harnesses.forEach((h) => h.cleanup()); dirs.forEach((d) => rmSync(d, { recursive: true, force: true })); });

function run({ comments = [], body = "## Order\n", state = true, definition = "# alpha\n", expectFail = false } = {}) {
  const h = createHarness({
    repos: { [HOME]: { issues: state ? [{ number: 5, title: "alpha State", labels: ["goal-agent:state"], body, comments }] : [] } },
  });
  harnesses.push(h);
  const d = mkdtempSync(join(tmpdir(), "stale-cwd-"));
  dirs.push(d);
  mkdirSync(join(d, ".claude", "agents"), { recursive: true });
  if (definition !== null) writeFileSync(join(d, ".claude", "agents", "alpha.md"), definition);
  const again = () => {
    const r = h.run(process.execPath, [script], { cwd: d, env: { GITHUB_REPOSITORY: HOME, GOAL_AGENT_NOW: NOW } });
    if (!expectFail) assert.equal(r.code, 0, r.stderr);
    return r;
  };
  const first = again();
  return { h, again, first };
}

test("a fresh Last run passes", () => {
  const { h } = run({ comments: [lastRun(ago(5.9))] });
  assert.equal(h.writes.all.length, 0);
});

test("a stale Last run opens one issue", () => {
  const { h } = run({ comments: [lastRun(ago(6.1))] });
  assert.equal(h.writes.newIssues.length, 1);
});

test("a missing Last run opens one issue", () => {
  const { h } = run({ comments: [{ body: "just a comment", updated_at: ago(1) }] });
  assert.equal(h.writes.newIssues.length, 1);
});

test("no State issue counts as missing", () => {
  const { h } = run({ state: false });
  assert.equal(h.writes.newIssues.length, 1);
});

test("a Halted agent opens nothing", () => {
  const { h } = run({ body: `## Order\n${HALT}\n`, comments: [lastRun(ago(50))] });
  assert.equal(h.writes.all.length, 0);
});

test("no duplicate while one is open", () => {
  const { h, again } = run({ comments: [lastRun(ago(9))] });
  again();
  assert.equal(h.writes.newIssues.length, 1);
  assert.equal(h.writes.comments.length, 0);
});

test("freshness is the comment's updated time, not its text", () => {
  const stale = lastRun(ago(8), `${AI}\n\n## Last run\n\n2026-01-10T11:59:00Z quick exit yes`);
  const { h } = run({ comments: [stale] });
  assert.equal(h.writes.newIssues.length, 1);
  const fresh = lastRun(ago(1), `${AI}\n\n## Last run\n\n2020-01-01T00:00:00Z`);
  const { h: h2 } = run({ comments: [fresh] });
  assert.equal(h2.writes.all.length, 0);
});

test("another agent's Last run does not count", () => {
  const other = lastRun(ago(1), "> *This was generated by AI: beta Goal agent.*\n\n## Last run\n");
  const { h } = run({ comments: [other] });
  assert.equal(h.writes.newIssues.length, 1);
});

const withCadence = (c) => `---
name: alpha
cadence: ${c}
---
# alpha
`;

test("a valid cadence sets the threshold to twice the cadence", () => {
  const def = withCadence("PT24H");
  const { h } = run({ comments: [lastRun(ago(47))], definition: def });
  assert.equal(h.writes.all.length, 0);
  const { h: h2 } = run({ comments: [lastRun(ago(49))], definition: def });
  assert.equal(h2.writes.newIssues.length, 1);
});

test("a short cadence keeps the 6-hour floor", () => {
  const def = withCadence("PT1H");
  const { h } = run({ comments: [lastRun(ago(5.9))], definition: def });
  assert.equal(h.writes.all.length, 0);
  const { h: h2 } = run({ comments: [lastRun(ago(6.1))], definition: def });
  assert.equal(h2.writes.newIssues.length, 1);
});

test("a cadence in days or with quotes is read", () => {
  const { h } = run({ comments: [lastRun(ago(40))], definition: withCadence('"P1D"') });
  assert.equal(h.writes.all.length, 0);
});

test("a missing cadence uses the 6-hour default", () => {
  const def = "---\nname: alpha\ngoal-agent-pin: abc\n---\n# alpha\n";
  const { h } = run({ comments: [lastRun(ago(5.9))], definition: def });
  assert.equal(h.writes.all.length, 0);
  const { h: h2 } = run({ comments: [lastRun(ago(6.1))], definition: def });
  assert.equal(h2.writes.newIssues.length, 1);
});

test("a missing definition file fails the workflow instead of defaulting", () => {
  const { h, first } = run({ comments: [lastRun(ago(40))], definition: null, expectFail: true });
  assert.notEqual(first.code, 0);
  assert.match(first.stderr, /definition/);
  assert.equal(h.writes.all.length, 0);
});

test("an unparsable cadence fails the workflow with a clear error", () => {
  for (const bad of ["hourly", "1H", "PT", "P1M", "PT0H"]) {
    const { h, first } = run({ comments: [lastRun(ago(1))], definition: withCadence(bad), expectFail: true });
    assert.notEqual(first.code, 0, bad);
    assert.match(first.stderr, /cadence/, bad);
    assert.match(first.stderr, new RegExp(bad), bad);
    assert.equal(h.writes.all.length, 0);
  }
});
